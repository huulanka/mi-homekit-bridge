export const locale = navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en'
const messages: Messages = locale === 'de' ? de : en

/** Page language, title and home-screen name follow the browser language. */
export function applyDocumentLanguage(): void {
  document.documentElement.lang = locale
  document.title = messages.title
  document.querySelector('meta[name="apple-mobile-web-app-title"]')?.setAttribute('content', messages.appTitle)
}

export type MessageKey = keyof Messages

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return messages[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}
